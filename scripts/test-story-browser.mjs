import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';

const base = process.env.QA_BASE_URL || 'http://127.0.0.1:4180';
const browser = await chromium.launch({ headless:true });
let checks = 0;
const verify = (condition, message) => { assert(condition, message); console.log('PASS '+message); checks++; };
await mkdir('test-results/uiux', { recursive:true });
try {
  const context = await browser.newContext({ viewport:{width:1440,height:900}, reducedMotion:'no-preference' });
  const page = await context.newPage();
  await page.goto(base+'/');
  await page.waitForFunction(() => document.querySelector('#solutions')?.dataset.pinned === 'true');
  await page.waitForFunction(() => performance.getEntriesByType('resource').filter(r => r.name.includes('/card-previews/')).length === 5);
  verify(true, 'All five small chooser images warm on landing-page arrival');
  const previews = await page.evaluate(() => performance.getEntriesByType('resource').filter(r => r.name.includes('/card-previews/')).map(r => r.name));
  let totalBytes = 0;
  for (const url of previews) {
    const response = await context.request.get(url);
    verify(response.headers()['cache-control']?.includes('immutable'), 'Versioned artwork has persistent browser caching');
    totalBytes += (await response.body()).length;
  }
  verify(totalBytes < 100000, 'All five chooser images total less than 100 KB');
  await page.evaluate(async () => {
    await document.fonts.ready;
    const pin = document.querySelector('.pin-spacer');
    const section = document.querySelector('#solutions');
    window.scrollTo({top:(pin || section).getBoundingClientRect().top + scrollY + 2,behavior:'instant'});
  });
  await page.waitForTimeout(800);
  verify(await page.locator('.usecase-panel').count() === 4, 'Original horizontal story contains four slides');
  const phone = page.locator('.tap-demo-phone'), card = page.locator('.tap-demo-card');
  verify(await phone.evaluate(e => getComputedStyle(e).backgroundColor) === 'rgb(5, 5, 5)', 'First-slide screen starts black');
  const a = await card.boundingBox(), b = await phone.boundingBox();
  await page.mouse.move(a.x+a.width/2,a.y+a.height/2); await page.mouse.down();
  const dx = b.x-(a.x+a.width)-3;
  await page.mouse.move(a.x+a.width/2+dx,a.y+a.height/2,{steps:10});
  verify(!await phone.locator('.phone-profile').count(), 'Three-pixel gap does not reveal the profile');
  await page.mouse.move(a.x+a.width/2+dx+5,a.y+a.height/2,{steps:2});
  await page.getByRole('button',{name:'Try again',exact:true}).waitFor();
  await page.mouse.up();
  verify(await phone.locator('.phone-profile').count() === 1, 'Physical card contact reveals the founder profile');
  await page.getByRole('button',{name:'Try again',exact:true}).click();
  verify(await phone.locator('svg').count() === 0, 'Blank phone screen contains no placeholder icon');
  verify(await page.locator('.tap-demo-cue svg path').count() === 4, 'Tap icon is one wave fan with a dot');
  await page.screenshot({path:'test-results/uiux/story-desktop.png'});
  await page.mouse.move(1100,450);
  await page.mouse.wheel(0,120);
  await page.waitForTimeout(50); const y1 = await page.evaluate(() => scrollY);
  await page.waitForTimeout(160); const y2 = await page.evaluate(() => scrollY);
  verify(y2 > y1+10, 'Mouse wheel continues moving after input stops');
  await page.waitForTimeout(1100); const y3 = await page.evaluate(() => scrollY);
  await page.waitForTimeout(200); const y4 = await page.evaluate(() => scrollY);
  verify(Math.abs(y4-y3) < 2, 'Wheel momentum decays to a complete stop');
  await page.mouse.wheel(0,240); await page.waitForTimeout(40); await page.mouse.down();
  const stopped = await page.evaluate(() => scrollY); await page.waitForTimeout(200); await page.mouse.up();
  verify(Math.abs(await page.evaluate(() => scrollY)-stopped) < 2, 'Pointer interaction stops remaining wheel momentum');
  verify(await page.locator('.story-tap-demo .story-labels svg').count() === 2, 'Tilted labels point to the card and phone');
  verify(await page.locator('.tap-demo-card img').getAttribute('src') === '/card-designs/maincard-v2.webp', 'First slide uses the owner-supplied card artwork');
  await page.getByRole('button',{name:'How it works: slide 2',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('.story-count')?.textContent === '2 / 4');
  await page.waitForTimeout(900);
  await page.locator('.story-qr-demo .story-tap-button').click();
  verify(await page.locator('.scan-demo-card > img').getAttribute('src') === '/brand-profile-qr.png', 'Second slide shows the back with the actual profile QR');
  verify(await page.locator('.scan-camera-screen .scan-line.is-scanning').isVisible(), 'Phone visibly scans the QR before loading the profile');
  await page.screenshot({path:'test-results/uiux/story-scan-desktop.png'});
  await page.locator('.scan-demo-phone .phone-profile').waitFor();
  verify(await page.locator('.scan-demo-phone').innerText().then(t=>t.includes('Ibraheem Anwar')), 'QR scan opens the same founder profile as tapping');
  await page.screenshot({path:'test-results/uiux/story-scanned-desktop.png'});
  await page.getByRole('button',{name:'How it works: slide 3',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('.story-count')?.textContent === '3 / 4');
  await page.waitForTimeout(1100);
  verify(await page.locator('.connected-phones .phone-profile').count() === 2, 'Third slide shows two separate profile phones');
  const umar = await page.locator('.connection-phone-right').innerText();
  verify(umar.includes('Umar Khan') && umar.includes('Entrepreneur') && umar.includes('Lahore') && ['WhatsApp','Instagram','Portfolio','Save profile'].every(label=>umar.includes(label)), 'Umar illustration includes supplied identity and visual contact boxes');
  verify(await page.locator('.connected-phones>.story-device').evaluateAll(es=>es.every(e=>getComputedStyle(e).transformOrigin.endsWith(' 0px'))),'Phones meet at their top corners');
  verify(await page.locator('.connection-phone-right img').getAttribute('src') === '/umar-story.webp', 'Third slide uses the supplied Umar portrait');
  const left=await page.locator('.connection-phone-left').boundingBox(),right=await page.locator('.connection-phone-right').boundingBox();
  verify(left.x+left.width >= right.x && left.x+left.width-right.x < 12, 'Tilted phone edges meet without covering either profile');
  await page.screenshot({path:'test-results/uiux/story-connect-desktop.png'});
  await page.getByRole('button',{name:'How it works: slide 4',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('.story-count')?.textContent === '4 / 4');
  await page.waitForTimeout(1000);
  verify(await page.locator('.story-dots button[aria-current=step]').getAttribute('aria-label') === 'How it works: slide 4', 'Original slide navigation reaches the fourth slide');
  await page.goto(base+'/order?product=profile');
  await page.getByRole('button',{name:'Black photography',exact:true}).waitFor();
  const timings = await page.evaluate(() => performance.getEntriesByType('resource').filter(r => r.name.includes('/card-previews/')).map(r => ({transfer:r.transferSize,decoded:r.decodedBodySize})));
  verify(timings.length === 5 && timings.every(t => t.transfer === 0 && t.decoded > 0), 'Chooser reuses warmed artwork without another network transfer');await page.screenshot({path:'test-results/uiux/order-builder-desktop.png',fullPage:true});
  await context.close();
  for (const height of [680,844]) {
    const mobile = await browser.newContext({viewport:{width:390,height},reducedMotion:'no-preference'});
    const p = await mobile.newPage(); await p.goto(base+'/#how-to-order');
    await p.waitForFunction(() => document.querySelector('#solutions')?.dataset.pinned === 'true');
    await p.waitForTimeout(1000);
    const controls = await p.locator('.story-controls').boundingBox(), status = await p.locator('.story-tap-demo .story-tap-status').boundingBox();
    verify(status.y >= 80 && controls.y < height && status.y+status.height <= controls.y+2, 'Public anchor opens slide one with instructions above visible controls at mobile height '+height);
    const cue=await p.locator('.tap-demo-cue').boundingBox(),target=await p.locator('.tap-demo-phone').boundingBox();verify(cue.x+cue.width < target.x,'Tap icon stays fully outside the phone at height '+height);await p.screenshot({path:`test-results/uiux/story-mobile-${height}.png`});
    await p.getByRole('button',{name:'How it works: slide 2',exact:true}).click();
    await p.waitForFunction(() => document.querySelector('.story-count')?.textContent === '2 / 4');await p.waitForTimeout(900);
    const scanStatus=await p.locator('.story-qr-demo .story-tap-status').boundingBox(),scanControls=await p.locator('.story-controls').boundingBox();
    verify(scanStatus.y+scanStatus.height <= scanControls.y+2, 'QR scene fits above mobile controls at height '+height);
    await p.locator('.story-qr-demo .story-tap-button').click();await p.screenshot({path:`test-results/uiux/story-scan-mobile-${height}.png`});
    await p.getByRole('button',{name:'How it works: slide 3',exact:true}).click();
    await p.waitForFunction(() => document.querySelector('.story-count')?.textContent === '3 / 4');await p.waitForTimeout(1000);
    const pair=await p.locator('.connected-profiles figcaption').boundingBox(),pairControls=await p.locator('.story-controls').boundingBox();
    verify(pair.y+pair.height <= pairControls.y+2, 'Connected profiles fit above mobile controls at height '+height);
    await p.screenshot({path:`test-results/uiux/story-connect-mobile-${height}.png`});
    if(height===844){await p.goto(base+'/#custom');await p.waitForTimeout(1000);verify(await p.getByRole('radio',{name:'5 stars',exact:true}).evaluate(e=>{const r=e.getBoundingClientRect();return r.top>=0&&r.bottom<=innerHeight;}),'Feedback hash opens the star form after pin layout');verify(await p.locator('.feedback-stars .ui-icon').count()===5 && await p.locator('.feedback-stars label').first().evaluate(e=>e.getBoundingClientRect().width)<=24,'Rating uses compact adjacent Streamline stars');await p.screenshot({path:'test-results/uiux/feedback-mobile.png'});await p.goto(base+'/order?product=profile');await p.getByRole('button',{name:'Black photography',exact:true}).waitFor();await p.screenshot({path:'test-results/uiux/order-builder-mobile.png',fullPage:true});}
    await mobile.close();
  }
  console.log(`PASS ${checks} story, momentum, contact and cache checks.`);
} finally { await browser.close(); }
